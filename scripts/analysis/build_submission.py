"""Assemble ``results/submission/``: Pareto fronts, ablations, gradient staleness.

Every figure holds a single optimizer. Each folder gets its figures, a
``csv/`` folder with the numbers behind them, and a ``.tex`` file with
booktabs tables of the same numbers. All values are at the protocol LRs of
``protocol_lr.py``, mean ± sample std over seeds per cell.

* ``pareto_fronts/``: ``<slice>_<optim>.png`` from ``plot_pareto_best_lr``.
* ``ablations/``: ``<slice>_<optim>_<arm>.png`` from ``plot_ablations_best_lr``, one
  per ablation arm. Only cells where every protocol seed finished are drawn;
  arms without such a cell are skipped and listed.
* ``gradient_staleness/``: probe and model-size figures and CSVs written by
  ``compare_probe_width`` and ``analyze_model_size`` (ReplaySGD only), copied
  under stable names.

  python scripts/analysis/build_submission.py [--refresh] [--rerun-staleness]
"""

