def load(refresh):
    groups = PA.all_groups()
    runs = P.load_runs(groups, refresh=refresh)
    by_group = {}
    for r in runs:
        by_group.setdefault(r['group'], []).append(r)
    return by_group, P.protocol_table()


def build_pareto(by_group, protocol):
    out = SUB / 'pareto_fronts'
    all_cells, missing, tables = [], [], []
    for dataset, angle in P.SLICES:
        for optim in P.OPTIMS:
            stem = f'{P.slice_id(dataset, angle)}_{optim}'
            cells, notes = PP.plot_slice(dataset, angle, protocol, by_group, out, optim, stem=stem)
            (out / f'{stem}.md').unlink(missing_ok=True)  # numbers live in csv/ and the .tex
            for c in cells:
                c.update(angle=angle, readout=readout_name(dataset), arm=c['family'])
            all_cells += cells
            missing += [{'dataset': dataset, 'angle': angle, 'optim': optim, 'note': n} for n in notes]
            if cells:
                p = protocol[(dataset, angle, optim)]
                cap = (f'{tex_escape(P.slice_title(dataset, angle))}, {P.OPTIM_NAME[optim]}: '
                       f'fine-tune and slow memory at lr$={p["lr"]:g}$, ER at lr$={p["er_lr"]:g}$ '
                       f'({tex_escape(p["er_source"])}). Readout {tex_escape(readout_name(dataset))}; '
                       'mean $\\pm$ sample std over seeds; bold = best ACC / lowest FRGT.')
                if any(c.get('at_chance') for c in cells):
                    cap += (' $^\\dagger$At chance accuracy (within 1 point): not drawn in the figure '
                            'and not on its front.')
                if notes:
                    cap += ' Missing: ' + '; '.join(tex_escape(n) for n in notes) + '.'
                tables.append(tex_table(cap, f'tab:pareto-{stem}',
                                        ['Family', 'Config', 'LR', 'ACC', 'FRGT', 'BWT', 'n'],
                                        cell_rows(cells, 'family'), bold_cols={3: 'max', 4: 'min'},
                                        align='lllcccc'))
    write_csv(out / 'csv' / 'pareto_cells.csv', all_cells, CELL_COLUMNS)
    write_csv(out / 'csv' / 'missing_at_protocol_lr.csv', missing, ['dataset', 'angle', 'optim', 'note'])
    write_protocol_csv(out / 'csv' / 'protocol_lrs.csv', protocol)
    tables.insert(0, lr_summary_table(protocol))
    note = ('The figures leave learning rates out; Table~\\ref{tab:pareto-lrs} lists them. Then one '
            'table per (dataset, optimizer). Cells are single learning rates; see '
            '\\texttt{csv/protocol\\_lrs.csv} for how each rate was chosen.')
    (out / 'pareto_fronts.tex').write_text(tex_doc('Pareto fronts at protocol learning rates', tables, note))
    return missing


def lr_summary_table(protocol):
    """Learning rates behind every Pareto figure, one row per (dataset, optimizer)."""
    rows = []
    for (dataset, angle, optim), p in protocol.items():
        rows.append({'_key': {}, 'cells': [
            tex_escape(P.slice_title(dataset, angle)), P.OPTIM_NAME[optim], f'{p["lr"]:g}',
            f'{p["er_lr"]:g}', tex_escape(p['er_source'])]})
    return tex_table('Learning rates in the Pareto figures. Fine-tune and slow memory use the '
                     'best rate of the $\\alpha=0$ learning-rate sweep (Task-IL ACC on split CIFAR); '
                     'the ER rate and its source are listed per row.', 'tab:pareto-lrs',
                     ['Dataset', 'Optimizer', 'Fine-tune / slow memory LR', 'ER LR', 'ER LR source'],
                     rows, align='lllll')


def write_protocol_csv(path, protocol):
    rows = []
    for (dataset, angle, optim), p in protocol.items():
        rows.append({'dataset': dataset, 'angle': angle, 'optim': optim,
                     'selection_readout': P.readout(dataset)[0], 'best_lr': p['lr'],
                     'er_lr': p['er_lr'], 'er_source': p['er_source'],
                     'lr_sweep': '; '.join(f'{lr:g}:{"" if m is None else f"{m:.2f}"}({n}/{t})'
                                           for lr, m, n, t in p['table'])})
    write_csv(path, rows, list(rows[0]))


def build_ablations(by_group, protocol):
    out = SUB / 'ablations'
    # Drop figures from earlier builds before writing.
    for old in out.glob('*.png'):
        old.unlink()
    all_cells, skipped, tables = [], [], []
    for dataset, angle in P.SLICES:
        for optim in P.OPTIMS:
            for _, arm, *_ in [p for p in PA.PANELS if p[0] == optim]:
                row = {'dataset': dataset, 'angle': angle, 'optim': optim, 'arm': arm}
                groups, reason = PA.arm_groups(dataset, angle, optim, arm)
                if groups is None:
                    skipped.append({**row, 'note': reason})
                    continue
                stem = f'{P.slice_id(dataset, angle)}_{optim}_{arm}'
                # Keep the figure only when the arm has a cell with every seed complete.
                probe = PA.plot_slice(dataset, angle, protocol, by_group, out, optims=(optim,),
                                      stem=stem, arms=(arm,))
                (out / f'{stem}.md').unlink(missing_ok=True)
                if not probe:
                    (out / f'{stem}.png').unlink(missing_ok=True)
                    skipped.append({**row, 'note': 'no cell with all seeds complete at the protocol LR'})
                    continue
                for c in probe:
                    c.update(angle=angle, readout=readout_name(dataset), optim=optim, family='ablation')
                all_cells += probe
                p = protocol[(dataset, angle, optim)]
                cap = (f'{tex_escape(P.slice_title(dataset, angle))}, {P.OPTIM_NAME[optim]}, '
                       f'\\texttt{{{tex_escape(arm)}}} at lr$={p["lr"]:g}$. Readout '
                       f'{tex_escape(readout_name(dataset))}; mean $\\pm$ sample std over seeds '
                       '42, 123, 7; bold = best ACC / lowest FRGT.')
                rows = cell_rows(sorted(probe, key=lambda c: (c['horizon_ratio'] or 0, c['K'] or 0,
                                                              c['memory_samples'] or 0,
                                                              c['refresh_batches'] or 0)), 'arm')
                tables.append(tex_table(cap, f'tab:abl-{stem}',
                                        ['Arm', 'Config', 'LR', 'ACC', 'FRGT', 'BWT', 'n'], rows,
                                        bold_cols={3: 'max', 4: 'min'}, align='lllcccc'))
    write_csv(out / 'csv' / 'ablation_cells.csv', all_cells, CELL_COLUMNS)
    write_csv(out / 'csv' / 'skipped.csv', skipped, ['dataset', 'angle', 'optim', 'arm', 'note'])
    note = ('One table per (dataset, optimizer, arm). Only cells where seeds 42, 123 and 7 all '
            'finished are shown. The grey references in the figures (fine-tune, slow memory, ER) '
            'are tabulated in \\texttt{pareto\\_fronts}; the figures draw those with at least two '
            'complete seeds. Two references have two: the rotMNIST AdEMAMix fine-tune (the '
            '$\\alpha=0$ learning-rate sweep at its best rate, seeds 42 and 123) and rotMNIST '
            '$30^\\circ$ ReplaySGD ER $K=5120$ (seed 42 finished with NaN accuracy).')
    (out / 'ablations.tex').write_text(tex_doc('Memory ablations at protocol learning rates', tables, note))
    return skipped


def build_staleness(rerun):
    out = SUB / 'gradient_staleness'
    if rerun:
        for script in STALENESS_SCRIPTS:
            subprocess.run([sys.executable, str(Path(__file__).with_name(script))],
                           cwd=P.REPO, check=True)
    # Named <plot type>_rotmnist_angle<θ> so each plot type sorts together.
    copies = {
        'model_size/model_size.png': 'model_size',
        'ablations/grad_staleness/probe_width_compare.png': 'probe_lr_vs_width',
        # Standalone single-panel figure, also as PDF.
        'ablations/grad_staleness/probe_batch_cos_r3.png': 'probe_per_gradient_staleness_r3',
        'ablations/grad_staleness/probe_batch_cos_r3.pdf': 'probe_per_gradient_staleness_r3',
        'ablations/grad_staleness/w100_pinned_lr/cos_agg_vs_n.png': 'probe_cos_agg_vs_tasks',
        'ablations/grad_staleness/w100_pinned_lr/phi_by_pos.png': 'probe_phi_by_position_in_task',
        'ablations/grad_staleness/w100_pinned_lr/top_k_share.png': 'probe_top_k_share',
    }
    csv_copies = {
        'model_size/model_size.csv': 'model_size',
        'ablations/grad_staleness/probe_width_compare.csv': 'probe_lr_vs_width',
        'ablations/grad_staleness/probe_per_step_sets.csv': 'probe_per_step',
    }
    # Drop copies left by earlier builds under other names.
    stale = ['rotmnist_angle*', 'probe_width100_vs_1000_*', 'probe_per_step_width100_*']
    for pattern in stale:
        for old in list(out.glob(pattern)) + list((out / 'csv').glob(pattern)):
            old.unlink()
    tables = []
    for angle in ANGLES:
        src = PLAN / f'rotmnist_angle{angle}'
        for rel, name in copies.items():
            if (src / rel).is_file():
                out.mkdir(parents=True, exist_ok=True)
                shutil.copy2(src / rel, out / f'{name}_rotmnist_angle{angle}{Path(rel).suffix}')
        for rel, name in csv_copies.items():
            if (src / rel).is_file():
                (out / 'csv').mkdir(parents=True, exist_ok=True)
                shutil.copy2(src / rel, out / 'csv' / f'{name}_rotmnist_angle{angle}.csv')
        tables += staleness_tables(angle, src)
    note = ('ReplaySGD \\texttt{slow\\_ema}, MLP 784--$w$--$w$--10 on rotMNIST. The probe '
            'compares three run sets: $w=100$ at a 3$\\times$ lower learning rate, and $w=100$ '
            'and $w=1000$ at the memory learning rate of the angle (0.1 at 9$^\\circ$, 0.3 at '
            '30$^\\circ$). The first two differ only in learning rate, the last two only in '
            'width. Probe metrics: mean $\\pm$ sample std over 3 seeds of the per-run mean over '
            'probe steps after the first two tasks, up to the last step the $w=1000$ runs '
            'reached (task 17). Per-batch probe figures use the $w=100$ runs at the memory '
            'learning rate.')
    (out / 'gradient_staleness.tex').write_text(
        tex_doc('Gradient staleness and model size (rotMNIST, ReplaySGD)', tables, note))


def staleness_tables(angle, src):
    tables = []
    path = src / 'ablations/grad_staleness/probe_width_compare.csv'
    if path.is_file():
        rows = []
        for r in csv.DictReader(path.open()):
            f = {k: float(v) for k, v in r.items() if v not in ('', None) and k != 'set'}
            cos_agg, cos_agg_sd = 1 - 2 * f['cos_dist_mean'], 2 * f['cos_dist_std']
            rows.append({'_key': {}, 'cells': [
                str(int(f['width'])), f'{f["r"]:g}', f'{f["lr"]:g}',
                pm(cos_agg, cos_agg_sd, 3), pm(f['cos_dist_mean'], f['cos_dist_std'], 3),
                pm(f['rel_E_mean'], f['rel_E_std'], 3), pm(f['proj_E_n_mean'], f['proj_E_n_std'], 3),
                pm(f['batch_cos_mean'], f['batch_cos_std'], 3), f'{f["frac_projE_pos"]:.2f}',
                str(int(f['n_seeds']))]})
        tables.append(tex_table(
            f'Staleness probe, rotMNIST {angle}$^\\circ$, learning rate vs width: rows with the '
            'same $w$ differ only in learning rate, rows with the same learning rate only in $w$. '
            'Columns: aggregate cosine '
            '$\\cos(\\mu^{\\mathrm{stale}},\\mu^{\\mathrm{fresh}})$, cosine distance, relative error '
            '$\\lVert E\\rVert/\\lVert\\mu^{\\mathrm{fresh}}\\rVert$, projected error '
            '$\\langle G_H,E\\rangle/\\lVert G_H\\rVert$, mean per-batch '
            '$\\cos(G_s,g^{\\mathrm{new}}_s)$, and the fraction of probe steps with '
            '$\\langle G_H,E\\rangle>0$.',
            f'tab:probe-a{angle}',
            ['$w$', '$r$', 'LR', r'$\cos_{\mathrm{agg}}$', 'cos.\\ dist.', 'rel.\\ err.',
             'proj.\\ err.', 'batch cos', '$P(>0)$', 'n'], rows, align='rrlccccccr'))
    path = src / 'model_size/model_size.csv'
    if path.is_file():
        rows = []
        for r in csv.DictReader(path.open()):
            cfg = (f'$r={float(r["horizon"]):g}$' if r['horizon'] else
                   f'$K={int(float(r["K"]))}$' if r['K'] else '--')
            rows.append({'_key': {3: float(r['ACC_mean']), 4: float(r['FRGT_mean'])}, 'cells': [
                tex_escape(r['family']), r['width'], cfg,
                pm(float(r['ACC_mean']), float(r['ACC_std'])),
                pm(float(r['FRGT_mean']), float(r['FRGT_std'])), r['n_seeds']]})
        tables.append(tex_table(
            f'Model size, rotMNIST {angle}$^\\circ$: fine-tune ($\\alpha=0$) and slow memory '
            '(\\texttt{slow\\_ema}, $\\alpha=1$) per width at the memory learning rate; ER '
            '($w=100$) at the Mammoth rate 0.2. Mean $\\pm$ sample std over seeds; bold = best '
            'ACC / lowest FRGT.', f'tab:model-size-a{angle}',
            ['Family', '$w$', 'Config', 'ACC', 'FRGT', 'n'], rows,
            bold_cols={3: 'max', 4: 'min'}, align='lrlccr'))
    return tables


def write_readme(protocol, missing, skipped):
    lines = ['# Submission figures and tables', '',
             'Generated by `scripts/analysis/build_submission.py`. Every figure holds one optimizer;',
             'every number is a single-LR cell (mean ± sample std over seeds). The protocol:',
             'fine-tune and slow memory at the α=0 best LR (Task-IL ACC on split CIFAR); ReplaySGD',
             "ER at Mammoth's ER LR where it exists, else the α=0 best LR. AdEMAMix ER (literature LRs",
             'are for SGD): on rotMNIST and CLEAR-10 the best LR of its ER LR sweep (cyclic rotMNIST,',
             'K = 1000); on seq-CIFAR the α=0 best LR, the rate those ER runs were launched at.', '',
             'CLEAR-10 AdEMAMix: slow memory and ER ran MultiStep(30,60,90). The fine-tune point comes',
             'from the MultiStep baseline (sweep 031eus33) once it finishes; until then from the',
             'constant-LR LR sweep, so it differs from the other arms in schedule.', '',
             'Colours: fine-tune black, slow memory blues (darker = larger r), ER reds (darker =',
             'larger K). Pareto cells at chance accuracy (mean ACC within 1 point of chance) are not',
             'drawn and not on the front; the tables list them with a dagger. seq-CIFAR-10 AdEMAMix',
             'slow memory r=10 uses 2 seeds (the seed-7 run died and was not rerun). rotMNIST',
             'ReplaySGD ER K=5120 at angle=30 uses 2 seeds: the seed=42 run finished with NaN ACC',
             'and the reseed launched with the wrong β2 default was deleted for being off-protocol.',
             'In ablation panels those are hollow references; the arm\'s own cells are',
             'filled greens by r (purple when the arm has no r). Ablation figures draw an arm\'s cell',
             'only where seeds 42, 123 and 7 all finished, and a reference where at least two seeds',
             'finished (rotMNIST AdEMAMix fine-tune: α=0 LR sweep, seeds 42 and 123; rotMNIST 30°',
             'ReplaySGD ER K=5120: seeds 7 and 123). No figure lists the configurations it leaves out;',
             'those are in the tables and `csv/skipped.csv`.', '',
             '| folder | figures | numbers |', '|---|---|---|',
             '| `pareto_fronts/` | `<slice>_<optim>.png` | `csv/pareto_cells.csv`, `pareto_fronts.tex`, `csv/protocol_lrs.csv` |',
             '| `ablations/` | `<slice>_<optim>_<arm>.png` | `csv/ablation_cells.csv`, `csv/skipped.csv`, `ablations.tex` |',
             '| `gradient_staleness/` | `model_size_*`, `probe_*` (rotMNIST, ReplaySGD) | `csv/`, `gradient_staleness.tex` |', '',
             'Each folder\'s `discussion.md` analyses its results. It is written by hand and not',
             'regenerated, so its numbers need checking after a rebuild with new runs.', '',
             '## Protocol learning rates', '', '| slice | optimizer | LR | ER LR |', '|---|---|---|---|']
    for (dataset, angle, optim), p in protocol.items():
        lines.append(f'| {P.slice_title(dataset, angle)} | {P.OPTIM_NAME[optim]} | {p["lr"]:g} | '
                     f'{p["er_lr"]:g} ({p["er_source"]}) |')
    lines += ['', '## Pareto families not plotted: no complete runs at the protocol LR', '']
    lines += [f'- {P.slice_title(m["dataset"], m["angle"])}: {m["note"]}' for m in missing]
    lines += ['', '## Ablation arms without a figure', '']
    lines += [f'- {P.slice_title(s["dataset"], s["angle"])}, {P.OPTIM_NAME[s["optim"]]}, '
              f'`{s["arm"]}`: {s["note"]}' for s in skipped]
    lines += ['', 'Rebuild: `python scripts/analysis/build_submission.py --refresh --rerun-staleness`', '']
    (SUB / 'README.md').write_text('\n'.join(lines))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--refresh', action='store_true', help='refetch every W&B group')
    ap.add_argument('--rerun-staleness', action='store_true',
                    help='rerun the probe and model-size scripts before copying their outputs')
    ap.add_argument('--only', choices=('pareto',),
                    help='rebuild only this folder; the others and their CSVs are left as they are')
    args = ap.parse_args()
    by_group, protocol = load(args.refresh)
    missing = build_pareto(by_group, protocol)
    if args.only == 'pareto':
        # Keep the ablation figures; the README lists their skipped arms from the last build.
        path = SUB / 'ablations' / 'csv' / 'skipped.csv'
        skipped = list(csv.DictReader(path.open())) if path.is_file() else []
        for s in skipped:
            s['angle'] = int(s['angle']) if s.get('angle') else None
    else:
        skipped = build_ablations(by_group, protocol)
        build_staleness(args.rerun_staleness)
    write_readme(protocol, missing, skipped)
    print(f'wrote {SUB}')


if __name__ == '__main__':
    main()
