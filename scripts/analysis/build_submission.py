def write_csv(path, rows, columns):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('w', newline='') as fh:
        w = csv.DictWriter(fh, fieldnames=columns, extrasaction='ignore')
        w.writeheader()
        for row in rows:
            w.writerow({k: (' '.join(map(str, v)) if isinstance(v, list) else v)
                        for k, v in row.items()})


def tex_escape(s):
    return (str(s).replace('\\', r'\textbackslash{}').replace('_', r'\_')
            .replace('&', r'\&').replace('%', r'\%').replace('#', r'\#')
            .replace('°', r'$^\circ$').replace('α', r'$\alpha$'))


def tex_label(s):
    """Point label (``r=1,α=4``, ``S'=16``) as LaTeX: each ``key=value`` in math."""
    parts = []
    for part in str(s).split(','):
        if '=' in part:
            key, val = part.split('=', 1)
            parts.append(f"${key.replace('α', chr(92) + 'alpha ')}={val}$")
        else:
            parts.append(tex_escape(part))
    return ', '.join(parts)


def pm(mu, sd, digits=1):
    if mu is None:
        return '--'
    return f'${mu:.{digits}f} \\pm {sd:.{digits}f}$'


def tex_table(caption, label, header, rows, bold_cols=(), align=None):
    """booktabs table; ``bold_cols`` = {col index: 'max' | 'min'} over numeric keys."""
    align = align or 'l' * len(header)
    lines = [r'\begin{table}[ht]', r'\centering\small', rf'\begin{{tabular}}{{{align}}}',
             r'\toprule', ' & '.join(header) + r' \\', r'\midrule']
    best = {}
    for col, mode in dict(bold_cols).items():
        vals = [r['_key'][col] for r in rows if r['_key'].get(col) is not None]
        if vals:
            best[col] = max(vals) if mode == 'max' else min(vals)
    for r in rows:
        cells = list(r['cells'])
        for col, b in best.items():
            if r['_key'].get(col) == b:
                cells[col] = cells[col].replace('$', '', 1)[::-1].replace('$', '', 1)[::-1]
                cells[col] = rf'$\mathbf{{{cells[col]}}}$'
        lines.append(' & '.join(cells) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular}', rf'\caption{{{caption}}}',
              rf'\label{{{label}}}', r'\end{table}', '']
    return '\n'.join(lines)


def tex_doc(title, tables, preamble_note):
    head = [f'% {title}', '% Generated by scripts/analysis/build_submission.py; do not edit by hand.',
            '% Needs: \\usepackage{booktabs}', r'\documentclass[11pt]{article}',
            r'\usepackage[margin=0.8in]{geometry}', r'\usepackage{booktabs}', r'\begin{document}',
            rf'\section*{{{tex_escape(title)}}}', preamble_note, '']
    return '\n'.join(head + tables + [r'\end{document}', ''])


def cell_rows(cells, kind_key):
    """Table rows; chance-level cells (``at_chance``) get a dagger and no bold."""
    rows = []
    for c in cells:
        chance = c.get('at_chance')
        rows.append({
            '_key': {} if chance else {3: c['acc'], 4: c['frgt']},
            'cells': [tex_escape(c[kind_key]), tex_label(c['label']) + ('$^\\dagger$' if chance else ''),
                      f'{c["lr"]:g}',
                      pm(c['acc'], c['acc_std']), pm(c['frgt'], c['frgt_std']),
                      pm(c['bwt'], c['bwt_std']), str(c['n'])],
        })
    return rows


def readout_name(dataset):
    acc, frgt, ro = P.readout(dataset)
    return f'{acc} / {frgt}' + (f' ({ro})' if ro else '')


